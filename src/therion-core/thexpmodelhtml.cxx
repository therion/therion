std::string thhtml_base64(const std::string & data) {
  static const char tbl[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  std::string r;
  r.reserve((data.size() + 2) / 3 * 4 + data.size() / 57 + 1);
  size_t i, line = 0;
  for (i = 0; i + 2 < data.size(); i += 3) {
    unsigned v = ((unsigned char) data[i] << 16) | ((unsigned char) data[i + 1] << 8) | (unsigned char) data[i + 2];
    r += tbl[(v >> 18) & 63];
    r += tbl[(v >> 12) & 63];
    r += tbl[(v >> 6) & 63];
    r += tbl[v & 63];
    if (++line == 19) {
      r += '\n';
      line = 0;
    }
  }
  if (i < data.size()) {
    unsigned v = (unsigned char) data[i] << 16;
    if (i + 1 < data.size()) v |= (unsigned char) data[i + 1] << 8;
    r += tbl[(v >> 18) & 63];
    r += tbl[(v >> 12) & 63];
    r += (i + 1 < data.size()) ? tbl[(v >> 6) & 63] : '=';
    r += '=';
  }
  return r;
}

std::string thhtml_escape(const std::string & s) {
  std::string r;
  for (char c : s) {
    switch (c) {
      case '&': r += "&amp;"; break;
      case '<': r += "&lt;"; break;
      case '>': r += "&gt;"; break;
      case '"': r += "&quot;"; break;
      default: r += c;
    }
  }
  return r;
}

